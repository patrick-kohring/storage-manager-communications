package com.storagemanager.communications.action.support;

import java.util.Map;
import java.util.UUID;

import com.storagemanager.communications.action.lead.LeadView;
import com.storagemanager.communications.messaging.EventEnvelope;
import com.storagemanager.communications.model.MessageType;
import com.storagemanager.communications.model.RecipientType;

/**
 * A fully-valid {@code SendCommunication} case for the harness: an envelope that passes <em>all</em>
 * {@code ActionProcessor} validation, together with the seed data the harness must install so the
 * action succeeds and produces exactly one send (lead-communication-action Property 1).
 *
 * <p>This is the reusable "happy path" fixture generated by
 * {@link ActionArbitraries#successfulActionCases()}. A sibling test wires it up with
 * {@link HarnessFixture} and then asserts the expected send mapping using the pre-computed
 * {@code expected*} fields below, which encode exactly what the processor should resolve.
 *
 * @param envelope              the well-formed envelope to feed {@code ActionProcessor.process}
 * @param leadId                the lead id (envelope payload {@code leadId} parsed to UUID)
 * @param leadView             the {@link LeadView} the port must return for {@code leadId}
 * @param templateName          the template name the action selects
 * @param templateIsFacility    whether the resolving template is facility-scoped (vs org-scoped)
 * @param emailContent          the template's email content (may be {@code null} when SMS-only)
 * @param smsContent            the template's SMS content (may be {@code null} when email-only)
 * @param leadPath              {@code true} for the LEAD recipient path, {@code false} for explicit
 * @param placeholderToJsonProperty the LEAD {@code placeholder -> jsonProperty} mappings to seed
 * @param expectedChannel       the channel the processor should resolve
 * @param expectedContact       the single contact value the processor should resolve
 * @param expectedContent       the personalized content the processor should produce
 * @param expectedRecipientType the audit recipient type ({@code LEAD} on lead path, {@code null} on explicit)
 * @param expectedCorrelationId the correlation id the processor should derive and carry to the send
 */
public record SuccessfulActionCase(
        EventEnvelope envelope,
        UUID leadId,
        LeadView leadView,
        String templateName,
        boolean templateIsFacility,
        String emailContent,
        String smsContent,
        boolean leadPath,
        Map<String, String> placeholderToJsonProperty,
        MessageType expectedChannel,
        String expectedContact,
        String expectedContent,
        RecipientType expectedRecipientType,
        UUID expectedCorrelationId
) {
}
